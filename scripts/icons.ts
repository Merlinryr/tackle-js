// Regenerates src/icons.ts from @phosphor-icons/core (MIT): `node scripts/icons.ts`.
// Only the glyphs the overlay uses are vendored, so the runtime stays dependency-free.
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = {
  open: 'circle',
  'in-progress': 'circle-notch',
  resolved: 'check-circle',
  verified: 'seal-check',
  low: 'arrow-down',
  high: 'arrow-up',
  urgent: 'warning',
  bug: 'bug',
  'replace-component': 'swap',
  layout: 'layout',
  style: 'paint-brush',
  copy: 'text-t',
  dots: 'dots-three',
  close: 'x',
  send: 'arrow-up',
  caret: 'caret-down',
  check: 'check',
  hash: 'hash',
  chat: 'chat-circle-dots',
  clip: 'copy',
  outline: 'bounding-box',
}

const inner = (name: string) => readFileSync(`node_modules/@phosphor-icons/core/assets/regular/${name}.svg`, 'utf8')
  .replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')

const body = Object.entries(NAMES).map(([k, v]) => `  '${k}': '${inner(v)}',`).join('\n')
writeFileSync('src/icons.ts', `// Generated by scripts/icons.ts from @phosphor-icons/core (MIT). Do not edit.\nexport const ICONS: Record<string, string> = {\n${body}\n}\n`)
